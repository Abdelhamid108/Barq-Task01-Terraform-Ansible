#!/usr/bin/env bash
set -euo pipefail

HEADER_BORDER="=================================================="

echo "${HEADER_BORDER}"
echo " Starting End-to-End AWS & Ansible Deployment"
echo "${HEADER_BORDER}"

# 1. Check required tools
echo "==> [1/5] Verifying local CLI prerequisites..."
command -v terraform >/dev/null 2>&1 || { echo "[ERROR] terraform is required but not installed." >&2; exit 1; }
command -v ansible-playbook >/dev/null 2>&1 || { echo "[ERROR] ansible-playbook is required but not installed." >&2; exit 1; }

# 2. Prepare SSH key and detect operator public IP
echo "==> [2/5] Preparing SSH key and detecting public IP..."
KEY="${SSH_KEY:-$HOME/.ssh/barq-task01}"
if [ ! -f "$KEY" ]; then
  echo "    Creating SSH key at $KEY"
  ssh-keygen -t ed25519 -N "" -f "$KEY" -C "barq-task" >/dev/null
fi

MY_IP="${SSH_ALLOWED_IP:-$(curl -fsS --max-time 10 https://checkip.amazonaws.com 2>/dev/null || curl -fsS --max-time 10 https://ifconfig.me 2>/dev/null)}"
MY_IP=$(echo "$MY_IP" | tr -d '[:space:]')
if [[ ! "$MY_IP" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then
  echo "[ERROR] Could not detect a valid IPv4 address (got '$MY_IP'). Set SSH_ALLOWED_IP=x.x.x.x" >&2
  exit 1
fi
echo "Detected Public IP: ${MY_IP}"
ALLOWED_CIDR="${MY_IP}/32"

cat > Terraform/terraform.auto.tfvars <<EOF
# GENERATED by deploy.sh - do not commit
ssh_allowed_cidr = "${ALLOWED_CIDR}"
public_key_path  = "${KEY}.pub"
private_key_path = "${KEY}"
EOF

# 3. Apply Terraform Infrastructure
echo "==> [3/5] Initializing and applying Terraform infrastructure..."
cd Terraform
terraform init
terraform apply -auto-approve
APP_PUBLIC_IP=$(terraform output -raw app_public_ip)
cd ..

# 4. Wait for SSH availability & cloud-init completion
echo "==> [4/5] Waiting for SSH access on App server (${APP_PUBLIC_IP})..."
until ssh -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o ConnectTimeout=5 -i "$KEY" ubuntu@"${APP_PUBLIC_IP}" "echo SSH Ready" >/dev/null 2>&1; do
  echo "    Waiting for EC2 instance initialization..."
  sleep 5
done

# 5. Install Ansible collections and run site playbook
echo "==> [5/5] Installing Ansible requirements and executing playbook..."
cd Ansible
ansible-galaxy collection install -r requirements.yml
ansible-playbook site.yml
cd ..

echo "${HEADER_BORDER}"
echo " Deployment Successfully Completed!"
echo " Access Spring Petclinic at http://${APP_PUBLIC_IP}"
echo "${HEADER_BORDER}"